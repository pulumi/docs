#!/usr/bin/env python3
"""glowup-autofix.py — the deterministic half of the post-open glow-up autofix.

Pre-verification (preverify-glowup.py) is the primary path: a glow-up PR
should open with every claim on its edited lines verified. This is the
fallback for what the pre-merge review still finds after it opens, since the
review reads the whole diff with more than the claim verifier (a claim the
page's own table contradicts, a sample output the source renders
differently). Those findings are addressed to the PR author, pulumi-bot,
which never answers, so before this they sat open until someone noticed.

One pass, run by `.github/workflows/content-review-glowup-autofix.yml`:

  select    decide, from the PR, its current author card (via
            review-worklist.py's JSON), and prior autofix comments, whether a
            pass should run now:
              fix       open 🚨/❓ findings on a review current at the head,
                        and passes remain
              escalate  findings still open and the pass budget is spent (or
                        the last pass left some unresolved): hand them to
                        the routed human team, once per PR
              none      anything else, with the reason
  answer    validate the model's dispositions against the closed set, fold
            in the deterministic post-check (a fix the re-verification had to
            revert is unresolved, whatever the model said), and render the
            `@claude … #update-review` answer comment, the PR body's
            "Post-open review findings" section, and the escalation comment.

Dispositions (closed set; `address-review:references:dispositions` minus the
two a bot cannot own, `accepted` and `deferred`, which need a human):

  fixed       the text now says what the source says (note: what changed)
  reverted    the glow-up's edit is withdrawn; master's text is back (note)
  refuted     the finding is wrong; `source` must cite what shows it (note)
  unresolved  none of the above could be done safely; a human decides

Bounds. At most MAX_PASSES passes per PR, counted from pulumi-bot comments
carrying the pass marker, and never two passes on the same head: the update
lane refreshes the card after a pass, and only a card current at a NEW head
can start the next one. A PR whose passes are spent escalates once.

Usage:
    glowup-autofix.py select --pr-json pr.json --worklist wl.json \
        --comments comments.json [--max-passes 2]
    glowup-autofix.py answer --select select.json --dispositions d.json \
        [--postcheck reverted.json] --commit <sha> --out-dir .autofix
    glowup-autofix.py --self-test
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

BOT = "pulumi-bot"
# The only login whose review cards count. Anyone who can comment can post a
# body carrying the card's markers, and the fix job hands the card to a model.
REVIEW_BOT = "github-actions[bot]"
# Logins that are automation, not people, for the stand-down checks.
AUTOMATION = {BOT, REVIEW_BOT, "claude[bot]"}
# Commit authors GitHub can't link to an account arrive with an empty login,
# so they are judged by email. These are the automation identities our own
# commits carry: the workflows commit as pulumi-bot <bot@pulumi.com> with a
# `Co-Authored-By: Claude <noreply@anthropic.com>` trailer, and gh lists the
# trailer as a second author. Any OTHER unlinked email is a person.
AUTOMATION_EMAILS = {"bot@pulumi.com", "noreply@anthropic.com"}
PAGE_DELIMITER = "----- PINNED-COMMENT-DELIMITER -----"
BRANCH_PREFIX = "content-review/glowup-"
MAX_PASSES = 2
PASS_MARKER = "GLOWUP_AUTOFIX"
ESCALATED_MARKER = "GLOWUP_AUTOFIX_ESCALATED"
SECTION = "Post-open review findings"
DISPOSITIONS = ("fixed", "reverted", "refuted", "unresolved")
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"

# `answered` is the head the pass read the card at; `pushed` is the head it
# left behind (equal when it pushed nothing). Only `answered` decides "this
# head already had its pass": keying on the pushed head made every refreshed
# card look already-answered, so pass 2 and escalation never ran.
#
# Both markers are read only as the comment's FIRST line, a line that is
# nothing but the marker: the renderers put it there and nothing
# model-supplied can reach it. Model text (a disposition's note or source)
# lands further down the same comment, and `_defang` below neutralizes any
# HTML comment in it, so a note like `done <!-- GLOWUP_AUTOFIX_ESCALATED -->`
# can neither forge a marker nor hide text from the rendered comment.
_PASS_RE = re.compile(rf"\A\s*<!--\s*{PASS_MARKER}\s+pass=(\d+)\s+answered=([0-9a-f]{{7,40}})"
                      rf"(?:\s+pushed=([0-9a-f]{{7,40}}))?\s*-->[ \t]*$", re.M)
_ESC_RE = re.compile(rf"\A\s*<!--\s*{ESCALATED_MARKER}(?:\s+head=[0-9a-f]*)?\s*-->[ \t]*$", re.M)


def _defang(text) -> str:
    """Neutralize HTML-comment delimiters in text we didn't write, so it
    renders literally instead of opening (or forging) a comment."""
    return re.sub(r"--!?>", "--&gt;", str(text or "").replace("<!--", "&lt;!--"))


def _login(c: dict) -> str:
    return ((c.get("user") or c.get("author") or {}).get("login") or "")


def prior_passes(comments: list[dict]) -> list[dict]:
    """Passes recorded by pulumi-bot. The budget lives in these comments, so
    deleting one resets it; only pulumi-bot's count, so nobody else can
    spend or forge it."""
    out = []
    for c in comments or []:
        if _login(c) != BOT:
            continue
        m = _PASS_RE.search(c.get("body") or "")
        if m:
            out.append({"pass": int(m.group(1)), "answered": m.group(2),
                        "pushed": m.group(3) or m.group(2), "at": c.get("created_at") or ""})
    return out


def _same(a: str, b: str) -> bool:
    a, b = (a or "").lower(), (b or "").lower()
    return bool(a and b) and (a.startswith(b) or b.startswith(a))


def _card_comments(comments: list[dict], marker: str) -> list[dict]:
    return [c for c in comments or []
            if _login(c) == REVIEW_BOT and marker in (c.get("body") or "")]


def cards(comments: list[dict]) -> tuple[str, str, str]:
    """(author card, reviewer brief, card updated_at) from the review bot's
    comments only. A multi-page card's pages are joined in page order with
    the delimiter review-worklist.py folds."""
    author = _card_comments(comments, "<!-- CLAUDE_REVIEW_AUTHOR -->")
    pages = []
    if author:
        first = author[-1]
        pages.append(first)
        m = re.search(r"<!-- CLAUDE_REVIEW 1/(\d+) -->", first.get("body") or "")
        total = int(m.group(1)) if m else 1
        for n in range(2, total + 1):
            nth = [c for c in comments or [] if _login(c) == REVIEW_BOT
                   and f"<!-- CLAUDE_REVIEW {n}/{total} -->" in (c.get("body") or "")]
            if nth:
                pages.append(nth[-1])
    brief = _card_comments(comments, "<!-- CLAUDE_REVIEW_BRIEF -->")
    updated = max((c.get("updated_at") or c.get("created_at") or "" for c in pages), default="")
    return (f"\n{PAGE_DELIMITER}\n".join(c.get("body") or "" for c in pages),
            (brief[-1].get("body") or "") if brief else "", updated)


# `F3: ...`, `F3 is wrong`, "accepting all open items": the reply shapes the
# card's How-to-answer section teaches.
_ANSWER_RE = re.compile(r"\bF\d+\b|\baccept(?:ing|ed)?\b", re.I)


def human_activity(pr: dict, comments: list[dict]) -> str:
    """Why a person owns this PR now, or "" if nobody has stepped in. A
    `reverted` disposition would otherwise overwrite their edit."""
    for c in pr.get("commits") or []:
        for a in c.get("authors") or []:
            login = a.get("login") or ""
            if login:
                if login not in AUTOMATION:
                    return f"{login} pushed to this PR"
                continue
            # No linked account: still a person unless the email is ours.
            email = (a.get("email") or "").strip().lower()
            if email not in AUTOMATION_EMAILS and not email.endswith("[bot]@users.noreply.github.com"):
                return f"{a.get('name') or email or 'an unlinked author'} pushed to this PR"
    for c in comments or []:
        login = _login(c)
        body = c.get("body") or ""
        # An answer to a finding, not a bare refresh: the Sentinel and the
        # brief tell people to post `@claude #update-review` just to refresh
        # a stale card, and that must not end the autofix for the PR.
        if login and login not in AUTOMATION and "#update-review" in body and _ANSWER_RE.search(body):
            return f"{login} answered the review card"
    return ""


def escalated(comments: list[dict]) -> bool:
    return any(_login(c) == BOT and _ESC_RE.search(c.get("body") or "") for c in comments or [])


def open_blocking(worklist: dict) -> list[dict]:
    return [i for i in (worklist.get("items") or [])
            if i.get("blocking") and not i.get("disposition")]


def select(pr: dict, worklist: dict, comments: list[dict], max_passes: int = MAX_PASSES) -> dict:
    head = pr.get("headRefOid") or ""
    ref = pr.get("headRefName") or ""
    author = (pr.get("author") or {}).get("login") or ""
    files = [f.get("path") for f in pr.get("files") or [] if f.get("path")]
    md = [f for f in files if f.endswith(".md")]
    base = {"pr": pr.get("number"), "head_sha": head, "head_ref": ref,
            "article": md[0] if len(md) == 1 else "", "open": [], "pass": 0}

    def out(action: str, reason: str, **kw) -> dict:
        return {**base, **kw, "action": action, "reason": reason}

    if author != BOT or not ref.startswith(BRANCH_PREFIX):
        return out("none", f"not a pulumi-bot glow-up ({author or '?'} / {ref or '?'})")
    if (pr.get("state") or "").upper() != "OPEN" or pr.get("isDraft"):
        return out("none", "PR is not open and ready")
    if len(md) != 1:
        return out("none", f"expected exactly one markdown file, found {len(md)}")
    who = human_activity(pr, comments)
    if who:
        return out("none", f"{who}; the autofix stands down on PRs a person has touched")
    if (worklist.get("surface") or "") != "v3" or worklist.get("parse_confidence") != "high":
        return out("none", "no parseable v3 author card")
    reviewed = worklist.get("reviewed_sha") or ""
    if not head or not reviewed or not head.startswith(reviewed[:7]) or not reviewed.startswith(head[:len(reviewed)]):
        return out("none", f"review is not current at the head ({reviewed[:7] or 'none'} vs {head[:7]})")
    items = open_blocking(worklist)
    if not items:
        return out("none", "no open blocking findings")
    opened = [{"id": i["id"], "bucket": i.get("bucket"), "anchor": i.get("anchor"),
               "summary": i.get("summary", "")} for i in items]
    was_escalated = escalated(comments)
    base["escalated"] = was_escalated
    passes = prior_passes(comments)
    n = max((p["pass"] for p in passes), default=0)
    this_head = [p for p in passes if _same(p["answered"], head)]
    if this_head:
        # A pass already answered this exact head (it pushed nothing, e.g.
        # every finding was refuted). Once the card has refreshed after that
        # answer, whatever is still open is past what automation can do.
        _a, _b, card_at = cards(comments)
        if card_at and card_at > max(p["at"] for p in this_head):
            if was_escalated:
                return out("none", "this head was answered and already escalated", open=opened)
            return out("escalate", f"pass {this_head[-1]['pass']} answered this head and "
                       f"{len(opened)} finding(s) are still open", open=opened, **{"pass": n})
        return out("none", "a pass already answered this head; waiting for the refreshed card", open=opened)
    if n >= max_passes:
        if was_escalated:
            return out("none", f"pass budget spent ({n}/{max_passes}) and already escalated", open=opened)
        return out("escalate", f"pass budget spent ({n}/{max_passes}) with {len(opened)} finding(s) open",
                   open=opened, **{"pass": n})
    return out("fix", f"{len(opened)} open blocking finding(s); pass {n + 1}/{max_passes}",
               open=opened, **{"pass": n + 1})


def _cell(text, cap: int = 200) -> str:
    t = _defang(" ".join(str(text or "").split())).replace("|", "\\|")
    return t if len(t) <= cap else t[: cap - 1] + "…"


def fold(sel: dict, dispositions: dict, postcheck: dict | None, changed: bool = True) -> list[dict]:
    """One row per open finding: the model's disposition, validated, with the
    post-check applied. Anything missing or malformed is `unresolved`, and so
    is a `fixed`/`reverted` when no change was pushed (the model failed, the
    post-check failed or was degraded, or the model claimed an edit it never
    made)."""
    given = {}
    for d in (dispositions or {}).get("findings") or []:
        if isinstance(d, dict) and d.get("id"):
            given[str(d["id"])] = d
    reverted_ranges = []
    for b in (postcheck or {}).get("blocks") or []:
        lo, hi = (b.get("pristine_lines") or [0, 0])[:2]
        reverted_ranges.append((int(lo), int(hi) if hi else int(lo)))

    def anchor_range(a: str):
        m = re.match(r"^L(\d+)(?:-L?(\d+))?", str(a or ""))
        return (int(m.group(1)), int(m.group(2) or m.group(1))) if m else None

    rows = []
    for f in sel.get("open") or []:
        d = given.get(f["id"], {})
        disp = str(d.get("disposition") or "").strip().lower()
        # Model-supplied: one line, and no HTML comment can survive into
        # the rendered answer, escalation, or PR-body section.
        note = _defang(" ".join(str(d.get("note") or "").split()))
        source = _defang(" ".join(str(d.get("source") or "").split()))
        why = ""
        if disp not in DISPOSITIONS:
            disp, why = "unresolved", "no valid disposition recorded"
        elif disp == "refuted" and not source:
            disp, why = "unresolved", "refutation cited no source"
        elif disp in ("fixed", "reverted", "refuted") and not note:
            disp, why = "unresolved", f"{disp} without a note"
        if disp in ("fixed", "reverted") and not changed:
            disp, why = "unresolved", "no verified change was pushed"
        rng = anchor_range(f.get("anchor"))
        if disp in ("fixed", "reverted") and rng and any(lo - 2 <= rng[1] and rng[0] <= hi + 2
                                                         for lo, hi in reverted_ranges):
            disp, why = "unresolved", "the change did not re-verify and was withdrawn"
        rows.append({"id": _defang(f["id"]), "bucket": f.get("bucket"), "anchor": f.get("anchor"),
                     "summary": _defang(" ".join(str(f.get("summary") or "").split())),
                     "disposition": disp,
                     "note": note if not why else (f"{why}. {note}".strip() if note else why),
                     "source": source})
    return rows


def _marker(sel: dict, commit: str) -> str:
    return (f"<!-- {PASS_MARKER} pass={sel.get('pass')} answered={sel.get('head_sha')} "
            f"pushed={commit} -->")


def render_answer(rows: list[dict], sel: dict, commit: str) -> str:
    """The `#update-review` mention. Only rows with something to record go
    in it; an unresolved row is left for the human the escalation names."""
    lines = []
    for r in rows:
        if r["disposition"] == "fixed":
            lines.append(f"{r['id']}: fixed in {commit[:7]} — {r['note']}")
        elif r["disposition"] == "reverted":
            lines.append(f"{r['id']}: fixed in {commit[:7]} by withdrawing the glow-up's edit "
                         f"(master's text restored) — {r['note']}")
        elif r["disposition"] == "refuted":
            lines.append(f"{r['id']}: this is wrong — {r['note']} Source: {r['source']}")
    if not lines:
        return ""
    body = [_marker(sel, commit),
            "@claude answering for the glow-up automation (pass "
            f"{sel.get('pass')} of {MAX_PASSES}):", ""]
    body += [f"- {ln}" for ln in lines]
    body += ["", "#update-review"]
    return "\n".join(body) + FOOTER


def render_pass_marker_only(sel: dict, commit: str, rows: list[dict]) -> str:
    """A pass that recorded nothing still has to count against the budget."""
    ids = ", ".join(r["id"] for r in rows) or "none"
    return (_marker(sel, commit) + "\n"
            f"Glow-up autofix pass {sel.get('pass')} of {MAX_PASSES} could not settle any open finding "
            f"({ids}); they are for the requested reviewer." + FOOTER)


def render_section(history: list[dict]) -> str:
    out = [f"## {SECTION}", "",
           "What the automated pass did with each blocking finding the pre-merge review raised "
           "after this PR opened. Anything `unresolved` was handed to the routed reviewer.", "",
           "| Pass | ID | Finding | Disposition | Note / source |", "| --- | --- | --- | --- | --- |"]
    for h in history:
        for r in h.get("rows") or []:
            ns = r.get("note", "")
            if r.get("source"):
                ns += f" Source: {r['source']}"
            out.append(f"| {h.get('pass')} ({(h.get('commit') or '')[:7]}) | {r['id']} | {_cell(r.get('summary'), 160)} | "
                       f"{r.get('disposition')} | {_cell(ns, 240)} |")
    return "\n".join(out) + "\n"


def splice_section(body: str, section_md: str) -> str:
    pat = re.compile(rf"^##\s+{re.escape(SECTION)}\s*$.*?(?=^##\s|\Z)", re.M | re.S)
    if pat.search(body or ""):
        return pat.sub(lambda _m: section_md.rstrip() + "\n\n", body, count=1)
    m = re.search(r"^##\s+Screenshot check\s*$", body or "", re.M)
    if m:
        return body[: m.start()] + section_md.rstrip() + "\n\n" + body[m.start():]
    return (body or "").rstrip() + "\n\n" + section_md


def history_from_body(body: str) -> list[dict]:
    """Earlier passes' rows, read back from the body's own section, so the
    section accumulates across passes without any state outside the PR."""
    m = re.search(rf"^##\s+{re.escape(SECTION)}\s*$(.*?)(?=^##\s|\Z)", body or "", re.M | re.S)
    if not m:
        return []
    passes: dict[str, dict] = {}
    for line in m.group(1).splitlines():
        cells = [c.strip() for c in re.split(r"(?<!\\)\|", line.strip())[1:-1]]
        if len(cells) != 5 or not re.match(r"^\d+ \(", cells[0]):
            continue
        pm = re.match(r"^(\d+) \(([0-9a-f]*)\)", cells[0])
        key = pm.group(1)
        h = passes.setdefault(key, {"pass": int(key), "commit": pm.group(2), "rows": []})
        h["rows"].append({"id": cells[1], "summary": cells[2].replace("\\|", "|"),
                          "disposition": cells[3], "note": cells[4].replace("\\|", "|"), "source": ""})
    return [passes[k] for k in sorted(passes, key=int)]


def render_escalation(sel: dict, rows: list[dict], teams: list[str]) -> str:
    who = " ".join(f"@{t}" for t in teams) or "the routed reviewer"
    open_rows = [r for r in rows if r["disposition"] == "unresolved"] or \
        [{"id": f["id"], "summary": f.get("summary", ""), "note": ""} for f in sel.get("open") or []]
    lines = [f"<!-- {ESCALATED_MARKER} head={sel.get('head_sha', '')[:7]} -->",
             f"{who}: this glow-up couldn't reach a clean review automatically, so these are yours "
             "to decide (fix, refute, or accept on the review card):", ""]
    for r in open_rows:
        tail = f" _(automation: {r['note']})_" if r.get("note") else ""
        lines.append(f"- **{r['id']}** — {_cell(r.get('summary'), 240)}{tail}")
    lines += ["", "Pre-verification receipts and every automated disposition are in the PR body."]
    return "\n".join(lines) + FOOTER


def cmd_select(a) -> int:
    pr = json.loads(Path(a.pr_json).read_text())
    wl = json.loads(Path(a.worklist).read_text()) if Path(a.worklist).exists() else {}
    comments = json.loads(Path(a.comments).read_text()) if Path(a.comments).exists() else []
    res = select(pr, wl, comments, a.max_passes)
    print(json.dumps(res, indent=2))
    print(f"glowup-autofix select #{res.get('pr')}: {res['action']} — {res['reason']}", file=sys.stderr)
    return 0


def cmd_answer(a) -> int:
    sel = json.loads(Path(a.select).read_text())
    disp = {}
    if a.dispositions and Path(a.dispositions).exists():
        try:
            disp = json.loads(Path(a.dispositions).read_text())
        except json.JSONDecodeError:
            disp = {}
    post = json.loads(Path(a.postcheck).read_text()) if a.postcheck and Path(a.postcheck).exists() else None
    changed = not _same(a.commit, sel.get("head_sha") or "")
    rows = fold(sel, disp, post, changed)
    od = Path(a.out_dir)
    od.mkdir(parents=True, exist_ok=True)
    answer = render_answer(rows, sel, a.commit)
    (od / "answer.md").write_text(answer or render_pass_marker_only(sel, a.commit, rows))
    body = Path(a.body).read_text() if a.body and Path(a.body).exists() else ""
    history = [h for h in history_from_body(body) if h["pass"] != sel.get("pass")]
    history.append({"pass": sel.get("pass"), "commit": a.commit, "rows": rows})
    (od / "body.md").write_text(splice_section(body, render_section(history)))
    unresolved = [r["id"] for r in rows if r["disposition"] == "unresolved"]
    # Escalate what this pass could not settle. A budget-spent PR whose
    # refreshed card still has open items escalates through `select` instead,
    # which lists the items actually open then, not ones this pass fixed.
    escalate = bool(unresolved) and not sel.get("escalated")
    (od / "rows.json").write_text(json.dumps({"rows": rows, "unresolved": unresolved,
                                              "escalate": escalate}, indent=2) + "\n")
    teams = [t for t in (a.teams or "").split() if t]
    (od / "escalation.md").write_text(render_escalation(sel, rows, teams))
    print(f"glowup-autofix answer: {len(rows)} finding(s); unresolved={unresolved}; escalate={escalate}",
          file=sys.stderr)
    return 0


def cmd_cards(a) -> int:
    comments = json.loads(Path(a.comments).read_text()) if Path(a.comments).exists() else []
    author, brief, _at = cards(comments)
    Path(a.author_out).write_text(author)
    if a.brief_out:
        Path(a.brief_out).write_text(brief)
    return 0


def cmd_escalation(a) -> int:
    sel = json.loads(Path(a.select).read_text())
    teams = [t for t in (a.teams or "").split() if t]
    Path(a.out).write_text(render_escalation(sel, [], teams))
    return 0


