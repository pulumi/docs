#!/usr/bin/env python3
"""Decide whether a comment really runs a review slash command.

Review commands are slash commands at the start of a line, anywhere in a
PR conversation comment, an inline review comment, or a review body:

  /update-review [text]  refresh the pinned review. The whole comment is the
                         request, so a dispute, an accept, or a "fix F1 and
                         F3" goes in the same comment (claude-update.yml).
  /new-review [text]     clear the review and run a fresh one from scratch
                         (claude-new.yml). Beats /update-review when both
                         appear.
  /social-review         re-run the social copy review
                         (claude-social-review.yml).
  /oversized-ack         in an Approve review of a `review:oversized` PR:
                         record that a human reviewed it by hand (the
                         Sentinel's G5 gate, read by
                         scripts/review-v3/sentinel.py, which can't import
                         this file from its sparse checkout).

`@claude` is not part of any command: a bare `@claude` is a request for the
general assistant (claude.yml) and nothing else. The retired `@claude …
#update-review` / `#new-review` shapes start nothing; the `legacy` entry
point below drives review-command-redirect.yml, which answers them with the
same request rewritten as a slash command.

The workflows' `if:` expressions can only substring-match, so they also fire
on a comment that merely *quotes* a command — an explainer with
`/update-review F2: …` in backticks, a quote-reply of the card's own
instructions (#21535: two of four card versions were unrequested). This
script is the precise second check the workflows run before spending
anything: it removes fenced code blocks, inline code spans, and blockquoted
lines, then looks for the command at the start of a line in what is left.

Four entry points, all side-effect free apart from the files `legacy --out`
and `quick` write:

  check    — one body (from an env var, never argv): does it run
             `/<command>`? Prints `fire=<bool>` and `reason=<text>` in
             GITHUB_OUTPUT form.
  pending  — given recent comments/reviews on a PR plus the in-flight
             workflow runs, is an explicit refresh already on its way? Used
             by the auto-refresh job so a push-then-comment sequence doesn't
             cancel the human's request through the per-PR concurrency group.
             Prints `yield=<bool>` and `reason=<text>`.
  legacy   — does a body use a retired `@claude … #<command>` shape (and no
             live slash command)? Prints `reply=<bool>` and `command=<name>`,
             and writes the redirect reply to `--out`.
  quick    — the two `/update-review` shapes the update lane answers without
             a model (claude-update.yml, after its write-access check):
               `/update-review accept F<n>[ F<n>…]` as the comment's first
               line records each named open finding as `accepted` by the
               commenter, through the lane's normal publish chain (it writes
               the `.review-update.json` the model would have);
               `/update-review approve` alone gets a one-line reply saying
               that isn't how a PR is approved, and changes nothing.
             Anything else, including a near miss, is `mode=model`: the
             existing model path, unchanged. Prints `mode=model|accept|reply`,
             `applied=<ids>`, and `reply=<bool>`.

Exit status is 0 for every decision; only a usage error is non-zero, so a
workflow step can't be knocked over by the input it is judging.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from datetime import datetime, timedelta, timezone

COMMANDS = ("update-review", "new-review", "social-review", "oversized-ack")
LEGACY_COMMANDS = ("update-review", "new-review")
REDIRECT_MARKER = "<!-- REVIEW_COMMAND_REDIRECT -->"
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

# Fenced blocks first (``` or ~~~, any info string, any length), then inline
# spans — a run of N backticks closed by the same run, per CommonMark — then
# whole blockquoted lines. Order matters: an inline-span regex run over a
# fence would pair the wrong backticks.
#
# The inline pattern deliberately stays on one line (no re.S): a code span
# can't cross a paragraph break, so a stray unpaired backtick must not pair
# with one paragraphs later and swallow a live request in between. Erring
# this way costs at most a run on a quoted command split across lines;
# erring the other way silently drops a real request.
_FENCE_RE = re.compile(r"^[ \t]{0,3}(`{3,}|~{3,})[^\n]*\n.*?^[ \t]{0,3}\1[ \t]*$", re.S | re.M)
_UNCLOSED_FENCE_RE = re.compile(r"^[ \t]{0,3}(`{3,}|~{3,})[^\n]*\n.*\Z", re.S | re.M)
_INLINE_RE = re.compile(r"(`+)(?!`)([^\n]+?)(?<!`)\1(?!`)")
_QUOTE_LINE_RE = re.compile(r"^[ \t]{0,3}>.*$", re.M)

# A command starts a line (up to three spaces of indent; four is an indented
# code block) and ends at whitespace or the end of the line, so
# `/update-reviewer` is not `/update-review`.
_COMMAND_RE = re.compile(r"^[ \t]{0,3}/(" + "|".join(COMMANDS) + r")(?![\w-])", re.M | re.I)
# The same token anywhere, as long as it isn't the tail of a path or URL.
_ANYWHERE_RE = {c: re.compile(r"(?<![\w/.-])/" + c + r"(?![\w-])", re.I) for c in COMMANDS}

# The retired shapes. GitHub's `contains()` is case-insensitive, so the old
# triggers matched `@Claude` too.
_MENTION_RE = re.compile(r"(?<![\w/.-])@claude(?![\w-])", re.I)
_LEGACY_TAG_RE = re.compile(r"(?<![\w-])#(" + "|".join(LEGACY_COMMANDS) + r")(?![\w-])", re.I)
# The hybrid: a slash command typed after a mention, `@claude /update-review
# …`. Not a command (it doesn't start the line), so it used to fall to the
# chat lane, which answered with the retired instructions (pulumi/docs#22286,
# three times). It gets the redirect's reply instead, like the hashtag shape.
_MENTION_SLASH_RE = re.compile(
    r"^[ \t]{0,3}@claude[ \t]+/(" + "|".join(LEGACY_COMMANDS) + r")(?![\w-])", re.M | re.I)
_LEGACY_STRIP_RE = re.compile(
    r"[ \t]*(?:(?<![\w/.-])@claude(?:[ \t]+/(?:" + "|".join(LEGACY_COMMANDS) + r"))?"
    r"|(?<![\w-])#(?:" + "|".join(LEGACY_COMMANDS) + r"))(?![\w-])[ \t]*", re.I)
# Text a command can't share a line with without changing what it means.
_BLOCK_START_RE = re.compile(r"^(?:`{3,}|~{3,}|>|#{1,6}\s|[-*+]\s|\d+[.)]\s|\|)")


def _normalize(text: str) -> str:
    # GitHub bodies often arrive with CRLF; `[ \t]*$` can't see past a `\r`,
    # which would leave a closed fence looking unclosed.
    return (text or "").replace("\r\n", "\n").replace("\r", "\n")


def strip_quoted(text: str) -> str:
    """Return `text` with code and blockquotes removed.

    Anything a reader would understand as "showing" rather than "saying":
    fenced blocks, inline spans, and `>`-prefixed lines. An unclosed fence
    swallows the rest of the comment, matching how GitHub renders it.
    """
    text = _normalize(text)
    text = _FENCE_RE.sub(" ", text)
    text = _UNCLOSED_FENCE_RE.sub(" ", text)
    text = _INLINE_RE.sub(" ", text)
    text = _QUOTE_LINE_RE.sub(" ", text)
    return text


def commands_in(body: str) -> list[str]:
    """The live commands in `body`, first appearance first, each once."""
    seen: list[str] = []
    for m in _COMMAND_RE.finditer(strip_quoted(body)):
        name = m.group(1).lower()
        if name not in seen:
            seen.append(name)
    return seen


def decide(body: str, command: str, exclude: str | None = None) -> tuple[bool, str]:
    """Should the `/<command>` workflow fire for `body`?

    `exclude` is the more decisive command that wins when both appear live
    (`/new-review` beats `/update-review`). Quoted material never counts for
    either: a quoted `/new-review` does not suppress a live `/update-review`.
    """
    live = commands_in(body)
    token = f"/{command}"
    if command not in live:
        if _ANYWHERE_RE[command].search(strip_quoted(body)):
            return False, f"{token} is not at the start of a line"
        if _ANYWHERE_RE[command].search(_normalize(body)):
            return False, f"{token} appears only inside code or a blockquote"
        return False, f"no {token}"
    if exclude and exclude in live:
        return False, f"/{exclude} present — the more decisive command wins"
    return True, f"live {token}"


def legacy_command(body: str) -> str | None:
    """The retired command `body` asks for, or None.

    A live `@claude` plus a live `#update-review` / `#new-review` is the old
    shape (`#new-review` wins, as it did), and so is a line that starts
    `@claude /update-review` or `@claude /new-review`. A body that also
    carries a live `/update-review` or `/new-review` already runs, so it
    needs no redirect.
    """
    live = strip_quoted(body)
    if not _MENTION_RE.search(live):
        return None
    tags = {m.group(1).lower() for m in _LEGACY_TAG_RE.finditer(live)}
    tags |= {m.group(1).lower() for m in _MENTION_SLASH_RE.finditer(live)}
    if not tags:
        return None
    if set(commands_in(body)) & set(LEGACY_COMMANDS):
        return None
    return "new-review" if "new-review" in tags else "update-review"


def convert(body: str, command: str) -> str:
    """`body` rewritten as `/<command>`, with the request text kept as-is.

    Only the live `@claude` and hashtag tokens go, wherever they sit — the
    two are often paragraphs apart, or in either order. Every other
    character the author wrote stays, code and quotes included, so the
    update lane reads the same request it would have. One plain line rides
    on the command's line; anything longer, or starting with markdown that
    would change meaning there, goes under it.
    """
    raw = _normalize(body)
    # Find the tokens in a copy where code and quotes are blanked out
    # character for character, so offsets still line up with `raw`.
    masked = raw
    for rx in (_FENCE_RE, _UNCLOSED_FENCE_RE, _INLINE_RE, _QUOTE_LINE_RE):
        masked = rx.sub(lambda m: re.sub(r"[^\n]", "\0", m.group(0)), masked)
    pieces, pos = [], 0
    for m in _LEGACY_STRIP_RE.finditer(masked):
        pieces += [raw[pos:m.start()], " "]
        pos = m.end()
    pieces.append(raw[pos:])

    # The token pattern never crosses a newline, so the lines stay aligned.
    # A line that held nothing but the tokens goes, and so does the blank
    # line it leaves doubled, so a trailing `#update-review` paragraph
    # doesn't leave a gap behind.
    lines: list[str] = []
    dropped = False
    for before, after in zip(raw.split("\n"), "".join(pieces).split("\n")):
        if after == before:
            if not (dropped and not before.strip() and lines and not lines[-1].strip()):
                lines.append(before)
            dropped = False
        elif after.strip():
            lines.append(after.strip())
            dropped = False
        else:
            dropped = True
    text = "\n".join(lines).strip()
    if not text:
        return f"/{command}"
    # Anything longer than one plain line starts a paragraph of its own, so
    # nothing under it (a `---`, a list) can restyle the command line.
    if "\n" in text or _BLOCK_START_RE.match(text):
        return f"/{command}\n\n{text}"
    return f"/{command} {text}"


def _fence_for(text: str) -> str:
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    return "`" * max(3, longest + 1)


def render_redirect(body: str, command: str, author: str, docs_url: str) -> str:
    suggestion = convert(body, command)
    fence = _fence_for(suggestion)
    who = f"@{author} — " if author else ""
    if _MENTION_SLASH_RE.search(strip_quoted(body)):
        lead = (f"🤖 {who}nothing ran: a review command has to start the line on its own, "
                f"without `@claude` in front. `@claude` is just for asking Claude something. ")
    else:
        lead = (f"🤖 {who}`@claude … #{command}` is retired, so nothing ran. Review commands are "
                "slash commands now; `@claude` is just for asking Claude something. ")
    lines = [
        REDIRECT_MARKER,
        lead + "To run it, post this as a **new** comment (editing the old one won't trigger it):",
        "",
        fence,
        suggestion,
        fence,
    ]
    if docs_url:
        lines += ["", f"Every review command: [Review commands]({docs_url})."]
    return "\n".join(lines) + FOOTER


# ---- quick: the deterministic /update-review shapes ------------------------
#
# pulumi/docs#22397: an author typed `/update-review Approve` believing it
# approved the PR. It reached the model as free text, which interpreted it
# as an accept — about five minutes a round trip, and only because the model
# guessed right. Two shapes are now answered by code, and only these two, in
# exactly this form: anything looser is a sentence, and sentences stay the
# model's to read. No synonyms (lgtm, ok, approve-as-accept): a word that
# means "accept" to one author means "approve" to the next.

QUICK_REPLY_MARKER = "<!-- REVIEW_QUICK_REPLY -->"
_ACCEPT_LINE_RE = re.compile(
    r"^[ \t]{0,3}/update-review[ \t]+accept((?:[ \t]+F\d+)+)[ \t]*$", re.I)
_APPROVE_RE = re.compile(r"^/update-review[ \t]+approve[.!?]*$", re.I)
ACCEPT_REASON_MAX = 300
ACCEPT_NO_REASON = "No reason given."


_SIGNATURE_RE = re.compile(r"^\s*---\s*\n\s*_?(?:Generated|Sent) (?:by|with|from)\b.*", re.M | re.S | re.I)


def parse_quick(body: str) -> tuple[str, list[str], str] | None:
    """`("accept", ids, reason)`, `("approve", [], "")`, or None.

    accept: the first non-blank line is exactly `/update-review accept`
    followed by one or more `F<n>` ids (deduplicated, upper-cased, in order)
    and nothing else. Whatever the comment says below that line is the
    acceptance reason, recorded verbatim on one line.
    approve: the whole comment is `/update-review approve`, optionally with
    trailing punctuation."""
    text = _normalize(body).strip()
    if not text:
        return None
    if _APPROVE_RE.match(text):
        return "approve", [], ""
    first, _, rest = text.partition("\n")
    m = _ACCEPT_LINE_RE.match(first)
    if not m:
        return None
    ids: list[str] = []
    for tok in m.group(1).split():
        fid = tok.upper()
        if fid not in ids:
            ids.append(fid)
    # A signature block under a `---` rule (an agent's "Generated by ..."
    # attribution) is not part of the reason.
    rest = _SIGNATURE_RE.split(rest, maxsplit=1)[0]
    reason = " ".join(rest.split())
    if len(reason) > ACCEPT_REASON_MAX:
        reason = reason[:ACCEPT_REASON_MAX - 1].rstrip() + "…"
    return "accept", ids, reason


def _ids_phrase(ids: list[str]) -> str:
    return ", ".join(ids)


def plan_accept(ids: list[str], card: dict) -> tuple[list[str], list[tuple[str, str]]]:
    """(applied, skipped) for an accept against the live card.

    `card` is `{"open": [...], "answered": set, "known": set}`: `open` the
    author-card 🚨/❓ ids with no REVIEW_STATE disposition, in card order;
    `known` every id on either card (✅ Resolved included). An id not open is
    skipped, with why: already answered (a disposition, ✅ Resolved, or
    moved to the reviewer's ⚠️ list), or not on this review at all."""
    applied: list[str] = []
    skipped: list[tuple[str, str]] = []
    for fid in ids:
        if fid in card["open"]:
            applied.append(fid)
        elif fid in card["known"]:
            skipped.append((fid, "already answered or not waiting on the author"))
        else:
            skipped.append((fid, "no such finding on this review"))
    return applied, skipped


def accept_update(applied: list[str], actor: str, reason: str) -> dict:
    """The `.review-update.json` an accept writes: one `accept` per id, the
    shape the v3 adjudication model writes, so apply-update.py records it
    exactly as it would the model's (REVIEW_STATE `accepted`, actor = the
    commenter, the row moved to the reviewer's ⚠️ list with a ✋ marker)."""
    note = reason or ACCEPT_NO_REASON
    return {
        "schema": 1,
        "case": "dispute",
        "history_summary": (f"{actor or 'the author'} accepted {_ids_phrase(applied)} as-is "
                            "(/update-review accept)")[:120],
        "findings": [{"id": fid, "action": "accept", "reason": note} for fid in applied],
    }


def render_accept_reply(applied: list[str], skipped: list[tuple[str, str]],
                        open_ids: list[str], author: str) -> str:
    who = f"@{author} — " if author else ""
    nope = "; ".join(f"{fid} ({why})" for fid, why in skipped)
    if applied:
        line = f"🤖 {who}accepted {_ids_phrase(applied)}. Didn't apply: {nope}."
    else:
        left = f" Open now: {_ids_phrase(open_ids)}." if open_ids else " Nothing is waiting on you."
        line = f"🤖 {who}nothing recorded. Didn't apply: {nope}.{left}"
    return f"{QUICK_REPLY_MARKER}\n{line}"


def render_approve_reply(open_ids: list[str] | None, author: str) -> str:
    who = f"@{author} — " if author else ""
    lines = [
        QUICK_REPLY_MARKER,
        f"🤖 {who}`/update-review approve` doesn't approve a PR, so nothing ran. Approval is a "
        "GitHub review (**Files changed → Review changes → Approve**) from someone other than "
        "the PR's author.",
    ]
    if open_ids:
        lines.append(f"To accept a finding as-is instead: `/update-review accept {open_ids[0]}` "
                     f"(open now: {_ids_phrase(open_ids)}).")
    elif open_ids is None:
        lines.append("To accept a finding as-is instead: `/update-review accept F<n>`.")
    else:
        lines.append("Nothing on the review is waiting on the author.")
    return "\n".join(lines)


def read_card(author_path: str | None, brief_path: str | None) -> dict | None:
    """The live v3 cards as `plan_accept` reads them, or None when there is
    no v3 author card to read (a v2 review, no review, an unreadable card).

    Parsing goes through the update lane's own walkers (apply-update.py and
    review_state.py), imported here and only here: the gate job's sparse
    checkout carries this file alone and never calls `quick`."""
    if not author_path or not os.path.isfile(author_path):
        return None
    try:
        import importlib.util
        from pathlib import Path
        here = Path(__file__).resolve().parent

        def _load(name: str, path: Path):
            spec = importlib.util.spec_from_file_location(name, path)
            mod = importlib.util.module_from_spec(spec)
            sys.modules.setdefault(name, mod)
            spec.loader.exec_module(mod)
            return mod

        au = _load("apply_update", here / "apply-update.py")
        author = Path(author_path).read_text(encoding="utf-8")
        brief = (Path(brief_path).read_text(encoding="utf-8")
                 if brief_path and os.path.isfile(brief_path) else "")
        state = au.review_state.parse_state(author)
        if state is None:
            return None
        rows = au._collect_rows(author, brief)
        resolved = au._collect_resolved_rows(author)
    except Exception as exc:  # noqa: BLE001 — any doubt goes to the model path
        print(f"::warning::command gate: couldn't read the review cards ({exc}); "
              "leaving the request to the model", file=sys.stderr)
        return None
    answered = set((state.get("findings") or {}).keys())
    open_ids = sorted(
        (fid for fid, r in rows.items()
         if r["doc"] == "author" and r["bucket"] in ("outstanding", "author-answer")
         and fid not in answered),
        key=lambda f: int(f[1:]))
    return {"open": open_ids, "answered": answered,
            "known": set(rows) | set(resolved) | answered}


def decide_quick(body: str, card: dict | None, actor: str) -> dict:
    """Everything `quick` emits, as data: `mode`, `applied`, `update` (the
    patch, accept only), and `reply` (text or "")."""
    parsed = parse_quick(body)
    if parsed is None:
        return {"mode": "model", "applied": [], "update": None, "reply": ""}
    kind, ids, reason = parsed
    if kind == "approve":
        return {"mode": "reply", "applied": [], "update": None,
                "reply": render_approve_reply(card["open"] if card else None, actor)}
    if card is None:
        # No v3 card to record against (a v2 review, or none yet): the
        # request goes to the model path as it always has.
        return {"mode": "model", "applied": [], "update": None, "reply": ""}
    applied, skipped = plan_accept(ids, card)
    reply = render_accept_reply(applied, skipped, card["open"], actor) if skipped else ""
    if not applied:
        return {"mode": "reply", "applied": [], "update": None, "reply": reply}
    return {"mode": "accept", "applied": applied,
            "update": accept_update(applied, actor, reason), "reply": reply}


def _parse_ts(value: str | None) -> datetime | None:
    if not value:
        return None
    try:
        return datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone(timezone.utc)
    except ValueError:
        return None


EXPLICIT_EVENTS = {"issue_comment", "pull_request_review_comment", "pull_request_review"}
IN_FLIGHT = {"queued", "in_progress", "waiting", "requested", "pending"}
# The same exclusion the workflows' own `if:` applies — exact logins, never
# a prefix or a `[bot]` heuristic. `claude[bot]` is the review itself (its
# footer quotes the commands); any other commenter, human or bot, who writes
# a live command gets a run and so must count as a request in flight.
EXCLUDED_LOGINS = {"claude[bot]"}


def pending_explicit(
    items: list[dict],
    runs: list[dict],
    command: str,
    since: datetime,
    exclude: str | None = None,
) -> tuple[bool, str]:
    """Is an explicit `/<command>` request already being served?

    `items` are issue comments, review comments, and reviews (any mix; each
    needs `user.login`, a body, and `created_at` or `submitted_at`). `runs`
    are workflow runs of the refresh workflow (`event`, `status`,
    `created_at`). Yield when a live request newer than `since` exists AND a
    run of an explicit event type is still in flight and was created after
    that request — a request whose run already finished may have evaluated
    an older head and must not suppress the refresh for the new push.
    """
    newest: datetime | None = None
    newest_by = ""
    for item in items:
        login = ((item.get("user") or {}).get("login") or "")
        if login in EXCLUDED_LOGINS:
            continue  # the workflow trigger excludes this login; it never starts a run
        ts = _parse_ts(item.get("created_at") or item.get("submitted_at"))
        if ts is None or ts < since:
            continue
        fire, _ = decide(item.get("body") or "", command, exclude)
        if fire and (newest is None or ts > newest):
            newest, newest_by = ts, login
    if newest is None:
        return False, f"no live /{command} request since {since.isoformat()}"
    for run in runs:
        if run.get("event") not in EXPLICIT_EVENTS:
            continue
        if (run.get("status") or "") not in IN_FLIGHT:
            continue
        run_ts = _parse_ts(run.get("created_at") or run.get("createdAt"))
        if run_ts is not None and run_ts >= newest - timedelta(seconds=5):
            return True, f"explicit /{command} by {newest_by} at {newest.isoformat()} has a run in flight"
    return False, f"explicit /{command} by {newest_by} at {newest.isoformat()} has no run in flight"


def _emit(pairs: dict[str, object]) -> None:
    for key, value in pairs.items():
        text = str(value).lower() if isinstance(value, bool) else str(value)
        print(f"{key}={text}")


def _cmd_check(args: argparse.Namespace) -> int:
    body = os.environ.get(args.body_env, "")
    title = os.environ.get(args.title_env, "") if args.title_env else ""
    fire, reason = decide(f"{body}\n{title}" if title else body, args.command, args.exclude)
    if not fire:
        print(f"::notice::command gate: not firing — {reason}", file=sys.stderr)
    _emit({"fire": fire, "reason": reason})
    return 0


def _cmd_legacy(args: argparse.Namespace) -> int:
    body = os.environ.get(args.body_env, "")
    command = legacy_command(body)
    if command is None:
        _emit({"reply": False, "command": ""})
        return 0
    author = os.environ.get(args.author_env, "") if args.author_env else ""
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(render_redirect(body, command, author, args.docs_url or ""))
    _emit({"reply": True, "command": command})
    return 0


def _cmd_quick(args: argparse.Namespace) -> int:
    body = os.environ.get(args.body_env, "")
    actor = os.environ.get(args.author_env, "") if args.author_env else ""
    # The card is read only for a body that parses: a model-path comment
    # never pays for (or risks) the import.
    card = read_card(args.author_card, args.brief_card) if parse_quick(body) else None
    out = decide_quick(body, card, actor)
    if out["update"] is not None:
        with open(args.update_out, "w", encoding="utf-8") as fh:
            json.dump(out["update"], fh, indent=2)
            fh.write("\n")
    if out["reply"]:
        with open(args.reply_out, "w", encoding="utf-8") as fh:
            fh.write(out["reply"] + "\n")
    _emit({"mode": out["mode"], "applied": " ".join(out["applied"]), "reply": bool(out["reply"])})
    return 0


def _load_json_list(path: str | None) -> list[dict]:
    if not path:
        return []
    try:
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return []
    if isinstance(data, dict):
        data = data.get("workflow_runs") or data.get("items") or []
    return [d for d in data if isinstance(d, dict)]


def _cmd_pending(args: argparse.Namespace) -> int:
    since = _parse_ts(args.since)
    if since is None:
        print("pending: --since must be an ISO-8601 timestamp", file=sys.stderr)
        return 2
    items: list[dict] = []
    for path in args.comments:
        items.extend(_load_json_list(path))
    runs = _load_json_list(args.runs)
    do_yield, reason = pending_explicit(items, runs, args.command, since, args.exclude)
    _emit({"yield": do_yield, "reason": reason})
    return 0


def _self_test() -> int:
    failures = 0

    def check(name: str, cond: bool) -> None:
        nonlocal failures
        print(f"  {'ok ' if cond else 'FAIL'} {name}")
        if not cond:
            failures += 1

    # -- decide ------------------------------------------------------------
    U, N = "update-review", "new-review"
    check("command first fires", decide("/update-review F2: sourced it", U, N)[0])
    check("command on a later line fires", decide("F2: sourced it from the Q3 report.\n/update-review", U, N)[0])
    check("bare command fires", decide("/update-review", U, N)[0])
    check("CRLF body fires", decide("/new-review\r\n", N)[0])
    check("up to three spaces of indent fire", decide("   /update-review", U, N)[0])
    check("four spaces is a code block", not decide("    /update-review", U, N)[0])
    check("mid-line does not fire", not decide("Fixed, thanks /update-review", U, N)[0])
    check("reason names mid-line", "start of a line" in decide("thanks /update-review", U, N)[1])
    check("a longer word is not the command", not decide("/update-reviewer", U, N)[0])
    check("a path is not the command", not decide("see scripts/update-review", U, N)[0])
    check("case-insensitive", decide("/Update-Review", U, N)[0])
    check("inline-code quote does not fire",
          not decide("Reply with `/update-review F<n>: …` to answer.", U, N)[0])
    check("a line that is only a code span does not fire", not decide("`/update-review`", U, N)[0])
    check("fenced quote does not fire",
          not decide("Use:\n```\n/update-review F1: fixed\n```\nthanks", U, N)[0])
    check("CRLF fence still closes",
          decide("```\r\n/update-review\r\n```\r\n/update-review F1: fixed\r\n", U, N)[0])
    check("tilde fence does not fire", not decide("~~~text\n/update-review\n~~~", U, N)[0])
    check("blockquote does not fire",
          not decide("> /update-review F2: …\n\nDone, thanks.", U, N)[0])
    check("live command beside a quoted one fires",
          decide("Per the card (`/update-review F2`):\n/update-review F2: the figure is from Q3", U, N)[0])
    check("unclosed fence swallows the rest", not decide("```\n/update-review", U, N)[0])
    check("a stray backtick before a live request does not swallow it",
          decide("One stray ` here.\n\n/update-review F1: default is 5 per the AWS reference\n\nSee `verify.py`.", U, N)[0])
    check("live /new-review beats /update-review", not decide("/update-review\n/new-review", U, N)[0])
    check("quoted /new-review does not suppress",
          decide("/update-review F1: fixed (not `/new-review`)", U, N)[0])
    check("the old shape is not a command", not decide("@claude F1: fixed #update-review", U, N)[0])
    check("new-review mode fires", decide("/new-review", N)[0])
    check("social-review fires", decide("/social-review", "social-review")[0])
    check("empty body", not decide("", U)[0])
    check("reason names the quote", "inside code" in decide("`/update-review`", U)[1])
    check("commands_in orders and dedupes",
          commands_in("/new-review\n/update-review\n/new-review") == [N, U])

    # -- legacy ------------------------------------------------------------
    check("old shape is legacy", legacy_command("@claude F2: sourced it #update-review") == U)
    check("old new-review is legacy", legacy_command("@claude #new-review\r\n") == N)
    check("#new-review wins in the old shape too", legacy_command("@claude #update-review #new-review") == N)
    check("@Claude counts (contains() was case-insensitive)", legacy_command("@Claude #update-review") == U)
    check("bare @claude is not legacy", legacy_command("@claude what does F2 mean?") is None)
    check("hashtag alone is not legacy", legacy_command("#update-review please") is None)
    check("quoted old shape is not legacy",
          legacy_command("the old shape was `@claude F1 #update-review`") is None)
    check("blockquoted old shape is not legacy", legacy_command("> @claude #update-review\n\nthanks") is None)
    check("a live slash command needs no redirect",
          legacy_command("@claude #update-review\n/update-review F1: fixed") is None)
    check("@claudette is not @claude", legacy_command("@claudette #update-review") is None)
    hybrid = "@claude /update-review F10 F12: accepting as-is"
    check("mention-first slash command runs nothing", not decide(hybrid, U, N)[0])
    check("mention-first slash command is legacy", legacy_command(hybrid) == U)
    check("mention-first /new-review is legacy", legacy_command("@Claude /new-review") == N)
    check("convert drops the mention and keeps one command",
          convert(hybrid, U) == "/update-review F10 F12: accepting as-is")
    check("mid-sentence slash command is not the hybrid",
          legacy_command("@claude please run /update-review") is None)
    check("quoted hybrid is not legacy", legacy_command("`@claude /update-review`") is None)
    check("convert keeps the request on one line",
          convert("@claude F2: the figure is from Q3 #update-review", U) == "/update-review F2: the figure is from Q3")
    check("convert of a bare request", convert("@claude #new-review\r\n", N) == "/new-review")
    check("convert keeps a multi-line request under the command",
          convert("@claude fix F1 and F3\n\n- F1: typo\n- F3: link #update-review", U)
          == "/update-review\n\nfix F1 and F3\n\n- F1: typo\n- F3: link")
    check("convert puts block markdown under the command",
          convert("@claude - accepting all open items #update-review", U)
          == "/update-review\n\n- accepting all open items")
    check("convert leaves untouched lines alone",
          convert("@claude F1: see\n\n    indented code\n#update-review", U)
          == "/update-review\n\nF1: see\n\n    indented code")
    apart = "@claude a few things:\n\nF1: fixed in abc123.\n\nF3: intentional, the API returns 7.\n\n#update-review"
    check("tokens paragraphs apart are still the old shape", legacy_command(apart) == U)
    check("convert keeps everything between them",
          convert(apart, U) == "/update-review\n\na few things:\n\nF1: fixed in abc123.\n\nF3: intentional, the API returns 7.")
    check("hashtag first, mention last", legacy_command("#update-review\n\nF2: sourced.\n\n@claude") == U)
    check("convert of the reversed order", convert("#update-review\n\nF2: sourced.\n\n@claude", U)
          == "/update-review F2: sourced.")
    fenced = "@claude F2: output:\n\n```\n$ grep '#update-review' log\n```\n\nSee above. #update-review"
    check("a fence between the tokens doesn't hide them", legacy_command(fenced) == U)
    check("convert leaves the tokens inside code alone",
          convert(fenced, U) == "/update-review\n\nF2: output:\n\n```\n$ grep '#update-review' log\n```\n\nSee above.")
    check("a hashtag-only paragraph leaves no gap behind",
          convert("@claude F1: fixed.\n\nF2: accepting as-is.\n\n#update-review\n\nthanks", U)
          == "/update-review\n\nF1: fixed.\n\nF2: accepting as-is.\n\nthanks")
    check("a rule under the request can't turn the command into a heading",
          convert("@claude #new-review\n\n---\n_footer_", N) == "/new-review\n\n---\n_footer_")
    check("convert leaves quoted and inline-code tokens alone",
          convert("@claude per `@claude #update-review`:\n> @claude F1 #update-review\nok #update-review", U)
          == "/update-review\n\nper `@claude #update-review`:\n> @claude F1 #update-review\nok")
    reply = render_redirect("@claude F1: ```x``` #update-review", U, "alice", "https://example.test/c#review-commands")
    check("reply carries the marker", reply.startswith(REDIRECT_MARKER))
    check("reply names the author", "@alice —" in reply)
    check("reply fence outlasts the body's backticks", "\n````\n/update-review F1: ```x```\n````\n" in reply)
    check("reply links the reference", "(https://example.test/c#review-commands)" in reply)
    check("reply's own command is quoted, so it can't fire", not commands_in(reply))
    check("reply is not itself a legacy request", legacy_command(reply) is None)
    check("reply ends with the footer", reply.endswith(FOOTER))

    # -- pending -----------------------------------------------------------
    since = datetime(2026, 9, 10, 20, 20, tzinfo=timezone.utc)
    live = {"user": {"login": "workprentice[bot]"}, "body": "/update-review I pushed a fix for F1",
            "created_at": "2026-09-10T20:35:02Z"}
    quoted = {"user": {"login": "someone"}, "body": "the pattern is `/update-review …`",
              "created_at": "2026-09-10T20:36:00Z"}
    old_shape = {"user": {"login": "alice"}, "body": "@claude F1 #update-review", "created_at": "2026-09-10T20:36:10Z"}
    bot_note = {"user": {"login": "claude[bot]"}, "body": "/update-review", "created_at": "2026-09-10T20:37:00Z"}
    other_bot = {"user": {"login": "eon-pulumi-agent[bot]"}, "body": "/update-review F1: sourced",
                 "created_at": "2026-09-10T20:36:30Z"}
    human = {"user": {"login": "alice"}, "body": "/update-review F2: fixed", "created_at": "2026-09-10T20:36:40Z"}
    old = {"user": {"login": "alice"}, "body": "/update-review F3", "created_at": "2026-09-10T19:00:00Z"}
    inflight = {"event": "issue_comment", "status": "in_progress", "created_at": "2026-09-10T20:35:06Z"}
    finished = {"event": "issue_comment", "status": "completed", "created_at": "2026-09-10T20:35:06Z"}
    auto = {"event": "workflow_dispatch", "status": "in_progress", "created_at": "2026-09-10T20:35:14Z"}
    earlier_run = {"event": "issue_comment", "status": "in_progress", "created_at": "2026-09-10T20:00:00Z"}

    check("live request + in-flight run yields", pending_explicit([live], [inflight], U, since, N)[0])
    check("quoted request does not yield", not pending_explicit([quoted], [inflight], U, since, N)[0])
    check("the retired shape starts no run, so it does not yield",
          not pending_explicit([old_shape], [inflight], U, since, N)[0])
    check("claude[bot]'s own comment does not count", not pending_explicit([bot_note], [inflight], U, since, N)[0])
    check("workprentice[bot] counts", pending_explicit([live], [inflight], U, since, N)[0])
    check("any other bot login counts",
          pending_explicit([other_bot], [{"event": "issue_comment", "status": "queued", "created_at": "2026-09-10T20:36:33Z"}],
                           U, since, N)[0])
    check("a human counts",
          pending_explicit([human], [{"event": "issue_comment", "status": "queued", "created_at": "2026-09-10T20:36:44Z"}],
                           U, since, N)[0])
    check("request older than window does not yield", not pending_explicit([old], [inflight], U, since, N)[0])
    check("finished run does not yield", not pending_explicit([live], [finished], U, since, N)[0])
    check("auto dispatch run is not explicit", not pending_explicit([live], [auto], U, since, N)[0])
    check("run older than the request does not count", not pending_explicit([live], [earlier_run], U, since, N)[0])
    check("review with submitted_at counts",
          pending_explicit([{"user": {"login": "bob"}, "body": "/update-review F1",
                             "submitted_at": "2026-09-10T20:34:00Z"}],
                           [{"event": "pull_request_review", "status": "queued", "created_at": "2026-09-10T20:34:03Z"}],
                           U, since, N)[0])
    check("no items", not pending_explicit([], [inflight], U, since)[0])

    # -- quick -------------------------------------------------------------
    check("accept parses", parse_quick("/update-review accept F1 F3") == ("accept", ["F1", "F3"], ""))
    check("accept verb is case-insensitive", parse_quick("/Update-Review ACCEPT f2")[1] == ["F2"])
    check("accept ids dedupe", parse_quick("/update-review accept F2 F2 F1")[1] == ["F2", "F1"])
    check("accept reason is the rest of the comment",
          parse_quick("/update-review accept F1\n\nhouse style,\n on purpose")[2] == "house style, on purpose")
    check("an attribution footer is not part of the reason",
          parse_quick("/update-review accept F1\nwhy\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_")[2] == "why")
    check("a plain --- rule is kept", parse_quick("/update-review accept F1\na\n---\nb")[2] == "a --- b")
    check("accept needs an id", parse_quick("/update-review accept") is None)
    check("accept with commas is not the grammar", parse_quick("/update-review accept F1, F3") is None)
    check("accept with prose on its line is not the grammar",
          parse_quick("/update-review accept F1 because reasons") is None)
    check("a synonym is not the grammar", parse_quick("/update-review lgtm F1") is None)
    check("approve parses", parse_quick("/update-review Approve") == ("approve", [], ""))
    check("approve takes trailing punctuation", parse_quick("/update-review approve!\r\n") is not None)
    check("approve plus text is the model's", parse_quick("/update-review approve, F1 is fine") is None)
    check("approve on a later line is the model's", parse_quick("thanks\n/update-review approve") is None)
    check("a plain refresh is the model's", parse_quick("/update-review") is None)
    card = {"open": ["F1", "F2"], "answered": {"F3"}, "known": {"F1", "F2", "F3", "F4"}}
    q = decide_quick("/update-review accept F1 F3 F9", card, "alice")
    check("accept applies the open ids", q["mode"] == "accept" and q["applied"] == ["F1"])
    check("accept writes one accept per id",
          [(e["id"], e["action"]) for e in q["update"]["findings"]] == [("F1", "accept")])
    check("accept reply names what didn't apply", "F3 (already" in q["reply"] and "F9 (no such" in q["reply"])
    check("a clean accept posts nothing", decide_quick("/update-review accept F2", card, "a")["reply"] == "")
    none = decide_quick("/update-review accept F4", card, "alice")
    check("nothing to apply is a reply, no publish", none["mode"] == "reply" and none["update"] is None)
    check("accept without a v3 card is the model's", decide_quick("/update-review accept F1", None, "a")["mode"] == "model")
    ap = decide_quick("/update-review approve", card, "alice")
    check("approve is a reply naming the open ids", ap["mode"] == "reply" and "open now: F1, F2" in ap["reply"])
    check("approve reply is three lines at most", len(ap["reply"].splitlines()) <= 3)
    check("approve reply's commands can't fire", not commands_in(ap["reply"]))
    check("accept reply's commands can't fire", not commands_in(q["reply"]))

    print("command-gate self-test:", "PASS" if failures == 0 else f"{failures} FAILED")
    return 1 if failures else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--self-test", action="store_true")
    sub = parser.add_subparsers(dest="cmd")

    chk = sub.add_parser("check", help="judge one comment body")
    chk.add_argument("--command", required=True, choices=COMMANDS, help="e.g. update-review")
    chk.add_argument("--exclude", default=None, choices=COMMANDS, help="command that wins when both appear live")
    chk.add_argument("--body-env", required=True, help="env var holding the body (never pass the body as an argument)")
    chk.add_argument("--title-env", default=None, help="env var holding an issue title to consider alongside the body")

    pen = sub.add_parser("pending", help="is an explicit request already in flight?")
    pen.add_argument("--command", required=True, choices=COMMANDS)
    pen.add_argument("--exclude", default=None, choices=COMMANDS)
    pen.add_argument("--since", required=True, help="ISO-8601; requests older than this are ignored")
    pen.add_argument("--comments", action="append", default=[], help="JSON list of comments/reviews (repeatable)")
    pen.add_argument("--runs", default=None, help="JSON list of workflow runs (gh run list --json or the REST shape)")

    leg = sub.add_parser("legacy", help="does a body use a retired @claude #<command> shape?")
    leg.add_argument("--body-env", required=True, help="env var holding the body")
    leg.add_argument("--author-env", default=None, help="env var holding the commenter's login")
    leg.add_argument("--docs-url", default=None, help="link to the review-command reference")
    leg.add_argument("--out", required=True, help="file the redirect reply is written to")

    qk = sub.add_parser("quick", help="answer `/update-review accept F<n>` / `approve` without a model")
    qk.add_argument("--body-env", required=True, help="env var holding the body")
    qk.add_argument("--author-env", default=None, help="env var holding the commenter's login")
    qk.add_argument("--author-card", default=None, help="the live v3 author card (absent: no v3 review)")
    qk.add_argument("--brief-card", default=None, help="the live v3 reviewer brief")
    qk.add_argument("--update-out", required=True, help="where an accept writes .review-update.json")
    qk.add_argument("--reply-out", required=True, help="where a reply's text is written")

    args = parser.parse_args(argv)
    if args.self_test:
        return _self_test()
    if args.cmd == "check":
        return _cmd_check(args)
    if args.cmd == "pending":
        return _cmd_pending(args)
    if args.cmd == "legacy":
        return _cmd_legacy(args)
    if args.cmd == "quick":
        return _cmd_quick(args)
    parser.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
